// print datatype of variable.

let x = 50; // the value of x is number.
let y = "Ram"; // the value of y is string.
let z = "101" // the value of z is also a string.

//Note : whatever data is present inside the double quotes, it will always be a string.

console.log(x); // 50
console.log(y); // Ram
console.log(z); // 101

