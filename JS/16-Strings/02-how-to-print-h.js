// 02-how-to-print-h

let str = "Coding School";
console.log(str[9]); // h

// access-with-.length-property
console.log(str.length-1); // 12
console.log(str.length-2); // 11

console.log(str[str.length-1]); // l
console.log(str[str.length-2]); // 0
console.log(str[str.length-3]); // 0
console.log(str[str.length-4]); // h