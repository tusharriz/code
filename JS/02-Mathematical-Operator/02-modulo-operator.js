// This is a modulo operator "%"

let a = 10;
let b = 2;

console.log(a/b); // ==>  2|10|5 ==> 5 is quotient
//                          10
//                           0

console.log(a%b); // ==>  2|10|5
//                          10
//                           0  ==> 0 is remainder

// we need remainder only to solve coding questions

console.log(10%2); // ==>  2|10|5
//                           10
//                            0  ==> 0 is remainder

// we need remainder only to solve coding questions

console.log(10%2); // 0
console.log(2%10); // 2 ==>  10|2|0
//                              0
//                              2  ==> 2 is remainder